const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

require('ts-node').register({ project: path.join(__dirname, '../tsconfig.json'), transpileOnly: true });
require('reflect-metadata');
const { MenuService } = require('../src/menu/menu.service');
const { CreditoEmpleadosService } = require('../src/credito-empleados/credito-empleados.service');
const { TiendaEmpleadosService } = require('../src/tienda-empleados/tienda-empleados.service');
const { AlmuerzosService } = require('../src/almuerzos/almuerzos.service');

function poolWith(handler = () => ({ rows: [], rowCount: 0 })) {
  const calls = [];
  return { calls, async query(statement, parameters = []) {
    calls.push({ statement, parameters });
    return handler(statement, parameters);
  } };
}

test('General conserva su almacenamiento y aparece siempre primero', async () => {
  const pool = poolWith((statement) => statement.includes('SELECT items')
    ? { rows: [{ items: [{ referencia: 'RES' }] }] }
    : { rows: [{ id: 'especial', nombre: 'Especial' }] });
  const menu = new MenuService(pool);
  assert.deepEqual(await menu.obtenerConfig('punto'), [{ referencia: 'RES' }]);
  assert.match(pool.calls[0].statement, /FROM menu_config/);
  assert.equal((await menu.listas('punto'))[0].id, 'general');
});

test('una lista adicional se consulta y guarda solo en el punto indicado', async () => {
  const pool = poolWith();
  const menu = new MenuService(pool);
  await assert.rejects(menu.obtenerConfig('otro-punto', 'especial'), error => error.getStatus() === 404);
  await assert.rejects(menu.guardarConfig('otro-punto', [], 'especial'), error => error.getStatus() === 404);
  assert.deepEqual(pool.calls[0].parameters, ['otro-punto', 'especial']);
  assert.match(pool.calls[1].statement, /WHERE punto_id = \$1 AND id = \$2/);
  assert.ok(pool.calls.every(call => !call.statement.includes('INSERT INTO menu_config')));
});

test('una lista publica adicional vacia no filtra precios de General', async () => {
  const pool = poolWith(statement => {
    if (statement.includes('FROM puntos_venta')) return { rows: [{ id: '1', nombre: 'Centro', lista_precio: 'catalogo' }] };
    if (statement.includes('SELECT items')) return { rows: [{ items: [] }] };
    if (statement.includes('SELECT id, nombre')) return { rows: [{ id: 'especial', nombre: 'Especial' }] };
    throw new Error('No debe consultar el catalogo general');
  });
  const tienda = await new MenuService(pool).tienda('centro', 'especial');
  assert.deepEqual(tienda.categorias, []);
  assert.equal(tienda.listaNombre, 'Especial');
});

test('crear lista valida su nombre y clona General con SQL parametrizado', async () => {
  const pool = poolWith((statement, parameters) => ({ rows: [{ id: parameters[0], nombre: parameters[2] }] }));
  const menu = new MenuService(pool);
  await assert.rejects(menu.crearLista('1', ' '), error => error.getStatus() === 400);
  await assert.rejects(menu.crearLista('1', 'x'.repeat(81)), error => error.getStatus() === 400);
  const lista = await menu.crearLista('1', ' Especial ');
  assert.equal(lista.nombre, 'Especial');
  assert.match(lista.id, /^[\da-f-]{36}$/);
  assert.match(pool.calls[0].statement, /SELECT items FROM menu_config/);
  assert.deepEqual(pool.calls[0].parameters.slice(1), ['1', 'Especial']);
});

test('usuarios sin asignacion no pueden administrar listas de otro punto', async () => {
  const pool = poolWith();
  await assert.rejects(new MenuService(pool).verificarPunto({ sub: '8', rol: 'despacho' }, '9'), error => error.getStatus() === 403);
  assert.deepEqual(pool.calls[0].parameters, ['8', '9']);
});

test('nomina devuelve ambas quincenas con cero para un mes sin compras', async () => {
  const pool = poolWith(() => ({ rows: [13, 27].map(day => ({ nomina_fecha: `2026-10-${day}`, total: '0', n_pedidos: '0', trabajadores: '0' })) }));
  const credito = new CreditoEmpleadosService(pool, {});
  const resumen = await credito.resumenNomina('2026-10');
  assert.deepEqual(resumen.map(item => item.total), [0, 0]);
  assert.deepEqual(pool.calls[0].parameters, ['2026-10-01']);
  assert.match(pool.calls[0].statement, /LEFT JOIN credito_empleados_pedidos/);
  await assert.rejects(credito.resumenNomina('2026-99'), error => error.getStatus() === 400);
});

test('comanda se asigna en PostgreSQL y no depende del orden de lectura', async () => {
  const pool = poolWith();
  await new CreditoEmpleadosService(pool, {}).onModuleInit();
  assert.ok(pool.calls.some(call => /numero_comanda bigint GENERATED BY DEFAULT AS IDENTITY/.test(call.statement)));
});

test('conteo de pendientes no tiene limite de listado y solo incluye abiertos', async () => {
  const pool = poolWith(() => ({ rows: [{ total: '527' }] }));
  const tienda = new TiendaEmpleadosService(pool);
  assert.deepEqual(await tienda.pendientes(), { total: 527 });
  assert.match(pool.calls[0].statement, /estado IN \('pendiente', 'facturado'\)/);
  assert.doesNotMatch(pool.calls[0].statement, /LIMIT/);
});

test('filtro pendientes excluye entregados antes de aplicar el limite', async () => {
  const pool = poolWith();
  await new TiendaEmpleadosService(pool).listarPedidos({ estado: 'pendientes' });
  assert.match(pool.calls[0].statement, /estado IN \('pendiente', 'facturado'\)/);
  assert.match(pool.calls[0].statement, /CONCAT\('1CSE', numero_comanda\)/);
});

test('reprogramacion vacia y cancelacion se rechazan sin escribir datos', async () => {
  const pool = poolWith();
  const almuerzos = new AlmuerzosService(pool, {});
  await assert.rejects(almuerzos.reprogramar({}, '1', '12:00', ' '), error => error.getStatus() === 400);
  await assert.rejects(almuerzos.cancelar('1', '123456'), error => error.getStatus() === 403);
  assert.equal(pool.calls.length, 0);
});

test('la razon de reprogramacion se guarda junto al nuevo horario', async () => {
  const pool = poolWith(statement => {
    if (statement.includes('AS ok')) return { rows: [{ ok: true }] };
    if (statement.includes('FROM usuarios')) return { rows: [{ nombre: 'Admin' }] };
    return { rows: [{ id: '1', punto_id: '2', motivo_reprogramacion: 'Alta demanda' }], rowCount: 1 };
  });
  const resultado = await new AlmuerzosService(pool, {}).reprogramar({ sub: '1', rol: 'desarrollador' }, '1', '13:00', 'Alta demanda');
  const update = pool.calls.find(call => call.statement.includes('UPDATE almuerzos_solicitudes'));
  assert.match(update.statement, /motivo_reprogramacion = \$6/);
  assert.deepEqual(update.parameters.slice(-2), ['13:00', 'Alta demanda']);
  assert.equal(resultado.motivo_reprogramacion, 'Alta demanda');
});

test('disponibilidad exige documento propio, almuerzo de hoy y hora iniciada', async () => {
  const pool = poolWith(() => ({ rows: [{ id: '1', estado: 'terminada' }], rowCount: 1 }));
  await new AlmuerzosService(pool, {}).disponible('1', '123456');
  assert.deepEqual(pool.calls[0].parameters, ['1', '123456']);
  assert.match(pool.calls[0].statement, /documento = \$2/);
  assert.match(pool.calls[0].statement, /dia = .*America\/Bogota/);
  assert.match(pool.calls[0].statement, /inicio <= now\(\)/);
  assert.match(pool.calls[0].statement, /COALESCE\(disponible_en, now\(\)\)/);
});